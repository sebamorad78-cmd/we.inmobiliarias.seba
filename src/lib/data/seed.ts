const local = (file: string, alt: string): PropertyImage => ({ url: `/img/${file}`, alt });

const daysAgo = (d: number) => new Date(Date.UTC(2026, 10, 10) - d * 86400000).toISOString();

type SeedInput = Omit<Property, "id" | "createdAt" | "updatedAt" | "status" | "featured" | "videoUrl" | "tourUrl" | "floor" | "orientation" | "professionalUse" | "mortgageEligible" | "showExactLocation" | "expenses"> &
  Partial<Pick<Property, "status" | "featured" | "floor" | "orientation" | "professionalUse" | "mortgageEligible" | "showExactLocation" | "expenses" | "tourUrl">> & { days: number };

function make(n: number, s: SeedInput): Property {
  const { days, ...rest } = s;
  return {
    status: "publicada",
    featured: false,
    videoUrl: null,
    tourUrl: null,
    floor: null,
    orientation: null,
    professionalUse: false,
    mortgageEligible: false,
    showExactLocation: false,
    expenses: null,
    ...rest,
    id: `prop_${String(n).padStart(3, "0")}`,
    createdAt: daysAgo(days),
    updatedAt: daysAgo(Math.max(0, days - 2)),
  };
}

